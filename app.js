let currentLang = localStorage.getItem("haytool_lang") || "TR";

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("haytool_lang", lang);

  // Buton aktifliklerini ayarla
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // data-i18n oge metinlerini degistir
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (i18n[lang] && i18n[lang][key]) {
      el.textContent = i18n[lang][key];
    }
  });

  // HTML lang attribute guncelle
  document.documentElement.lang = lang.toLowerCase();

  // Ekran goruntusu guncelle (TR/ENG uyumlu)
  const previewImg = document.getElementById("preview-img");
  if (previewImg) {
    previewImg.src = lang === "TR" ? "ekrangoruntusu/tr.png" : "ekrangoruntusu/eng.png";
  }
}

// Sayfa yuklendiginde
document.addEventListener("DOMContentLoaded", () => {
  setLanguage(currentLang);

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      setLanguage(btn.dataset.lang);
    });
  });

  // Kedi maskotuna tiklandiginda miyav animasyonu
  const cat = document.querySelector(".cat-mascot");
  if (cat) {
    cat.addEventListener("click", () => {
      cat.style.transform = "scale(1.3) rotate(-15deg)";
      setTimeout(() => {
        cat.style.transform = "";
      }, 300);
    });
  }
});
